def standardize(train_x, other_x):
    mean = train_x.mean(axis=0)
    std = train_x.std(axis=0)
    std[std < 1e-6] = 1.0
    return (train_x - mean) / std, (other_x - mean) / std, mean, std


def propensity_overlap_weights(propensity_x, actions, indices):
    x = propensity_x[indices]
    labels = actions[indices]
    x_scaled, _, _, _ = standardize(x, x)
    channel_weights = []
    for action_index in range(A_DIM):
        y = labels[:, action_index]
        if len(np.unique(y)) < 2 or min(np.bincount(y)) < 2:
            channel_weights.append(np.ones(len(indices), dtype=np.float32))
            continue
        model = LogisticRegression(C=0.25, max_iter=1000, class_weight="balanced")
        model.fit(x_scaled, y)
        probability = np.clip(model.predict_proba(x_scaled)[:, 1], 0.05, 0.95)
        overlap = np.where(y == 1, 1.0 - probability, probability)
        channel_weights.append(overlap.astype(np.float32))
    weights = np.mean(np.stack(channel_weights, axis=1), axis=1)
    return np.clip(weights / max(weights.mean(), 1e-6), 0.25, 4.0)


def fitting_weights(data, indices, mode):
    if mode == "unweighted":
        return np.ones(len(indices), dtype=np.float32)
    episode = data["episode_weight"][indices]
    if mode == "episode":
        return episode / max(episode.mean(), 1e-6)
    propensity = propensity_overlap_weights(
        data["propensity_x"], data["actions"], indices
    )
    if mode == "propensity":
        return propensity
    combined = propensity * episode
    return combined / max(combined.mean(), 1e-6)


def fit_ridge(data, train_indices, target_index, mode, alpha):
    observed = np.isfinite(data["target"][train_indices, target_index])
    selected = train_indices[observed]
    if len(selected) < 8 or len(np.unique(data["groups"][selected])) < 3:
        return None
    x = data["x"][selected]
    mean = x.mean(axis=0)
    std = x.std(axis=0)
    std[std < 1e-6] = 1.0
    y = (
        data["target"][selected, target_index]
        - data["base"][selected, target_index]
    ) / S_STD[target_index]
    all_weights = fitting_weights(data, train_indices, mode)
    weight_lookup = dict(zip(train_indices.tolist(), all_weights.tolist()))
    weights = np.asarray([weight_lookup[index] for index in selected])
    model = Ridge(alpha=alpha)
    model.fit((x - mean) / std, y, sample_weight=weights)
    return {"model": model, "mean": mean, "std": std}


def predict_ridge(fitted, data, indices, target_index):
    if fitted is None:
        return data["base"][indices, target_index]
    correction = fitted["model"].predict(
        (data["x"][indices] - fitted["mean"]) / fitted["std"]
    )
    return data["base"][indices, target_index] + correction * S_STD[target_index]


def choose_configuration(data, outer_train, target_index):
    observed = np.isfinite(data["target"][outer_train, target_index])
    candidates = outer_train[observed]
    groups = data["groups"][candidates]
    unique_groups = np.unique(groups)
    if len(candidates) < 10 or len(unique_groups) < 4:
        return "unweighted", 100.0
    splitter = GroupKFold(n_splits=min(4, len(unique_groups)))
    scores = defaultdict(list)
    for inner_train_local, inner_validation_local in splitter.split(
        candidates, groups=groups
    ):
        inner_train = candidates[inner_train_local]
        inner_validation = candidates[inner_validation_local]
        for mode in WEIGHT_MODES:
            for alpha in RIDGE_ALPHAS:
                fitted = fit_ridge(
                    data, inner_train, target_index, mode, alpha
                )
                prediction = predict_ridge(
                    fitted, data, inner_validation, target_index
                )
                truth = data["target"][inner_validation, target_index]
                scores[(mode, alpha)].extend(np.abs(prediction - truth).tolist())
    return min(scores, key=lambda key: np.mean(scores[key]))


def choose_safe_method(data, outer_train, target_index,
                       validation_active_only=False):
    """Select persistence, raw JEPA, or adapter using inner patient CV only."""
    observed = np.isfinite(data["target"][outer_train, target_index])
    candidates = outer_train[observed]
    groups = data["groups"][candidates]
    unique_groups = np.unique(groups)
    if len(candidates) < 10 or len(unique_groups) < 4:
        return "persistence", None, None
    splitter = GroupKFold(n_splits=min(4, len(unique_groups)))
    scores = defaultdict(list)
    for inner_train_local, inner_validation_local in splitter.split(
        candidates, groups=groups
    ):
        inner_train = candidates[inner_train_local]
        inner_validation = candidates[inner_validation_local]
        if validation_active_only:
            inner_validation = inner_validation[data["active"][inner_validation]]
            if len(inner_validation) == 0:
                continue
        truth = data["target"][inner_validation, target_index]
        scores[("persistence", None, None)].extend(np.abs(
            data["current"][inner_validation, target_index] - truth
        ).tolist())
        scores[("base_jepa", None, None)].extend(np.abs(
            data["base"][inner_validation, target_index] - truth
        ).tolist())
        for mode in WEIGHT_MODES:
            for alpha in RIDGE_ALPHAS:
                fitted = fit_ridge(
                    data, inner_train, target_index, mode, alpha
                )
                prediction = predict_ridge(
                    fitted, data, inner_validation, target_index
                )
                scores[("adapter", mode, alpha)].extend(
                    np.abs(prediction - truth).tolist()
                )
    if not scores:
        return "persistence", None, None
    return min(scores, key=lambda key: np.mean(scores[key]))


