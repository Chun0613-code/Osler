RIDGE_ALPHAS = (0.1, 1.0, 10.0, 100.0)


def _value(row, name, default=np.nan):
    value = row.get(name, default)
    return default if pd.isna(value) else float(value)


def target_vector(row):
    target = np.full(S_DIM, np.nan, dtype=np.float32)
    for index, (_, target_column) in TARGET_COLUMNS.items():
        value = _value(row, target_column)
        if index == 9 and np.isnan(value):
            value = _value(row, "osmolality_derived_tp6")
        if index == 1 and np.isnan(value):
            bicarbonate = _value(row, "bicarbonate_tp6")
            if not np.isnan(bicarbonate):
                value = 6.1 + np.log10(max(bicarbonate, 0.1) / 1.2)
        target[index] = value
    return target


def episode_features(sequence):
    active = sequence > 0.05
    action_exposure = sequence.mean(axis=0)
    active_channels = int((action_exposure > 0.05).sum())
    total = float(action_exposure.sum())
    purity = float(action_exposure.max() / total) if total > 0 else 0.0
    simultaneous = float((active.sum(axis=1) > 1).mean())
    isolated = float(active_channels == 1 and simultaneous == 0.0)
    return action_exposure, np.array(
        [active_channels / A_DIM, purity, simultaneous, isolated],
        dtype=np.float32,
    )


@torch.no_grad()
def build_examples(model, frame, device):
    examples = []
    age_columns = [
        "glucose_age_hr", "ph_age_hr", "bicarbonate_age_hr",
        "anion_gap_age_hr", "potassium_age_hr", "map_age_hr",
        "sodium_age_hr", "osmolality_age_hr", "creatinine_age_hr",
        "urine_output_age_hr",
    ]
    for row_index, row in frame.iterrows():
        state = _state_from_row(row)
        sequence, history = _action_data(row)
        if state is None or sequence is None:
            continue
        state_normalized = s2vec(state)
        history = np.zeros(A_DIM * 2, dtype=np.float32) if history is None else np.asarray(
            history, dtype=np.float32
        )
        state_tensor = torch.as_tensor(
            state_normalized, dtype=torch.float32, device=device
        ).unsqueeze(0)
        history_tensor = torch.as_tensor(
            history, dtype=torch.float32, device=device
        ).unsqueeze(0)
        predicted, _, _ = model.rollout(
            state_tensor,
            torch.as_tensor(sequence, dtype=torch.float32, device=device).unsqueeze(0),
            history_tensor,
        )
        base_normalized = predicted[0, -1].cpu().numpy()
        base_physical = base_normalized * S_STD + S_MEAN
        target = target_vector(row)
        action_exposure, episode = episode_features(sequence)
        ages = np.asarray([
            min(_value(row, column, 6.0), 24.0) / 24.0
            for column in age_columns
        ], dtype=np.float32)
        dka_active = bool(row.get("dka_active_t", False))
        time_from_onset = min(max(_value(row, "hours_since_onset", 0.0), 0.0), 72.0) / 72.0
        adapter_features = np.concatenate([
            state_normalized,
            base_normalized - state_normalized,
            action_exposure,
            history,
            episode,
            ages,
            np.asarray([float(dka_active), time_from_onset], dtype=np.float32),
        ]).astype(np.float32)
        propensity_features = np.concatenate([
            state_normalized,
            history,
            ages,
            np.asarray([float(dka_active), time_from_onset], dtype=np.float32),
        ]).astype(np.float32)
        actual_directions = _actual_directions(row, state)
        latent = model.encode_state(state_tensor, history_tensor)
        symbolic = model.symbolic_outputs(
            latent,
            torch.as_tensor(
                action_exposure, dtype=torch.float32, device=device
            ).unsqueeze(0),
            delta_hours=sequence.shape[0] * DT,
        )
        examples.append({
            "row_index": int(row_index),
            "subject_id": int(row["subject_id"]),
            "stay_id": int(row["stay_id"]),
            "active_dka": dka_active,
            "current_physical": np.asarray([
                state[name] for name in STATE_KEYS
            ], dtype=np.float32),
            "base_physical": base_physical.astype(np.float32),
            "target_physical": target,
            "adapter_features": adapter_features,
            "propensity_features": propensity_features,
            "action_exposure": action_exposure.astype(np.float32),
            "action_active": (action_exposure > 0.05).astype(np.int64),
            "episode_weight": float(0.25 + 0.75 * episode[1] / (1.0 + episode[2])),
            "episode": episode,
            "actual_directions": actual_directions,
            "symbolic_probabilities": symbolic["proposal_logits"].softmax(
                dim=-1
            )[0].cpu().numpy(),
        })
    return examples


