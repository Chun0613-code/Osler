def fit_ensemble(data, train_indices, target_index, mode, alpha, rng,
                 members=20):
    models = []
    main = fit_ridge(data, train_indices, target_index, mode, alpha)
    if main is not None:
        models.append(main)
    groups = np.unique(data["groups"][train_indices])
    for _ in range(members - 1):
        sampled_groups = rng.choice(groups, size=len(groups), replace=True)
        sampled = np.concatenate([
            train_indices[data["groups"][train_indices] == group]
            for group in sampled_groups
        ])
        fitted = fit_ridge(data, sampled, target_index, mode, alpha)
        if fitted is not None:
            models.append(fitted)
    return models


def ensemble_predict(models, data, indices, target_index):
    if not models:
        prediction = data["base"][indices, target_index]
        return prediction, np.zeros_like(prediction), np.ones_like(prediction)
    predictions = np.stack([
        predict_ridge(model, data, indices, target_index) for model in models
    ])
    mean = predictions.mean(axis=0)
    std = predictions.std(axis=0)
    threshold = PHYSICAL_STABLE_THRESHOLDS[target_index]
    current = data["current"][indices, target_index]
    directions = np.where(
        predictions - current < -threshold, 0,
        np.where(predictions - current > threshold, 2, 1),
    )
    agreement = np.max(np.stack([
        (directions == direction).mean(axis=0) for direction in (0, 1, 2)
    ]), axis=0)
    return mean, std, agreement


def direction(values, current, target_index):
    threshold = PHYSICAL_STABLE_THRESHOLDS[target_index]
    delta = values - current
    return np.where(delta < -threshold, 0, np.where(delta > threshold, 2, 1))


def temperature_scale(probabilities, labels):
    if len(labels) < 10:
        return 1.0
    logits = np.log(np.clip(probabilities, 1e-7, 1.0))

    def objective(log_temperature):
        temperature = np.exp(log_temperature)
        scaled = logits / temperature
        scaled -= scaled.max(axis=1, keepdims=True)
        probability = np.exp(scaled)
        probability /= probability.sum(axis=1, keepdims=True)
        return -float(np.log(probability[np.arange(len(labels)), labels] + 1e-12).mean())

    result = minimize_scalar(objective, bounds=(-3.0, 4.0), method="bounded")
    return float(np.exp(result.x))


def apply_temperature(probabilities, temperature):
    logits = np.log(np.clip(probabilities, 1e-7, 1.0)) / temperature
    logits -= logits.max(axis=-1, keepdims=True)
    scaled = np.exp(logits)
    return scaled / scaled.sum(axis=-1, keepdims=True)


def expected_calibration_error(probabilities, labels, bins=8):
    confidence = probabilities.max(axis=1)
    prediction = probabilities.argmax(axis=1)
    correct = prediction == labels
    ece = 0.0
    for low, high in zip(np.linspace(0, 1, bins + 1)[:-1],
                         np.linspace(0, 1, bins + 1)[1:]):
        selected = (confidence > low) & (confidence <= high)
        if selected.any():
            ece += selected.mean() * abs(
                confidence[selected].mean() - correct[selected].mean()
            )
    return float(ece)


def probability_metrics(probabilities, labels):
    prediction = probabilities.argmax(axis=1)
    one_hot = np.eye(3)[labels]
    return {
        "n": int(len(labels)),
        "accuracy": round(float((prediction == labels).mean()), 4),
        "mean_confidence": round(float(probabilities.max(axis=1).mean()), 4),
        "ece": round(expected_calibration_error(probabilities, labels), 4),
        "brier": round(float(((probabilities - one_hot) ** 2).sum(axis=1).mean()), 4),
    }


def bootstrap_mae_difference(rows, method, baseline, active_only=True,
                             seed=7, samples=2000):
    relevant = [row for row in rows if (row["active_dka"] or not active_only)]
    stays = sorted({row["stay_id"] for row in relevant})
    rng = np.random.default_rng(seed)
    differences = []
    for _ in range(samples):
        selected_stays = rng.choice(stays, size=len(stays), replace=True)
        method_errors = []
        baseline_errors = []
        for stay in selected_stays:
            for row in relevant:
                if row["stay_id"] != stay or not np.isfinite(row["truth"]):
                    continue
                method_errors.append(abs(row[method] - row["truth"]) / row["scale"])
                baseline_errors.append(abs(row[baseline] - row["truth"]) / row["scale"])
        if method_errors:
            differences.append(np.mean(method_errors) - np.mean(baseline_errors))
    if not differences:
        return None
    return {
        "normalized_mae_difference": round(float(np.mean(differences)), 5),
        "bootstrap_95_ci": [
            round(float(np.quantile(differences, 0.025)), 5),
            round(float(np.quantile(differences, 0.975)), 5),
        ],
    }


def summarize_numerical(rows, active_only):
    selected = [row for row in rows if row["active_dka"] or not active_only]
    report = {}
    for method in (
        "persistence", "base_jepa", "adapter", "ensemble_adapter",
        "safe_hybrid", "active_safe_hybrid"
    ):
        errors = [
            abs(row[method] - row["truth"]) / row["scale"]
            for row in selected if np.isfinite(row["truth"])
        ]
        report[method] = {
            "n": len(errors),
            "normalized_mae": round(float(np.mean(errors)), 5) if errors else None,
        }
    per_state = {}
    for target_index in ADAPTED_STATE_INDICES:
        name = STATE_KEYS[target_index]
        state_rows = [row for row in selected if row["target_index"] == target_index]
        values = {}
        for method in (
            "persistence", "base_jepa", "ensemble_adapter", "safe_hybrid",
            "active_safe_hybrid"
        ):
            errors = [abs(row[method] - row["truth"]) for row in state_rows]
            values[method] = round(float(np.mean(errors)), 4) if errors else None
        per_state[name] = {"n": len(state_rows), **values}
    report["per_state_mae"] = per_state
    report["adapter_vs_base_jepa"] = bootstrap_mae_difference(
        rows, "ensemble_adapter", "base_jepa", active_only=active_only
    )
    report["adapter_vs_persistence"] = bootstrap_mae_difference(
        rows, "ensemble_adapter", "persistence", active_only=active_only
    )
    report["safe_hybrid_vs_base_jepa"] = bootstrap_mae_difference(
        rows, "safe_hybrid", "base_jepa", active_only=active_only
    )
    report["safe_hybrid_vs_persistence"] = bootstrap_mae_difference(
        rows, "safe_hybrid", "persistence", active_only=active_only
    )
    report["active_safe_hybrid_vs_persistence"] = bootstrap_mae_difference(
        rows, "active_safe_hybrid", "persistence", active_only=active_only
    )
    return report


def summarize_ablation(rows, active_only):
    selected = [row for row in rows if row["active_dka"] or not active_only]
    methods = [
        "persistence", "base_jepa",
        *[f"ensemble_{mode}" for mode in WEIGHT_MODES],
    ]
    return {
        method: {
            "n": int(sum(bool(np.isfinite(row["truth"])) for row in selected)),
            "normalized_mae": round(float(np.mean([
                abs(row[method] - row["truth"]) / row["scale"]
                for row in selected if np.isfinite(row["truth"])
            ])), 5),
        }
        for method in methods
    }


def run_crossfit(examples, seed=17):
    data = arrays(examples)
    unique_stays = np.unique(data["groups"])
    splitter = GroupKFold(n_splits=min(4, len(unique_stays)))
    rng = np.random.default_rng(seed)
    numerical_rows = []
    symbolic_before = []
    symbolic_after = []
    symbolic_labels = []
    symbolic_changed = []
    symbolic_stays = []
    configurations = Counter()
    safe_configurations = Counter()
    active_safe_configurations = Counter()

    for outer_train, outer_test in splitter.split(
        np.arange(len(examples)), groups=data["groups"]
    ):
        test_stays = set(data["groups"][outer_test].tolist())
        if test_stays & set(data["groups"][outer_train].tolist()):
            raise RuntimeError("patient leakage in outer split")

        train_probability = []
        train_label = []
        for index in outer_train:
            directions = examples[index]["actual_directions"]
            for state_index in ADAPTED_STATE_INDICES:
                if directions[state_index] >= 0:
                    train_probability.append(
                        examples[index]["symbolic_probabilities"][state_index]
                    )
                    train_label.append(directions[state_index])
        temperature = temperature_scale(
            np.asarray(train_probability), np.asarray(train_label, dtype=np.int64)
        )

        for target_index in ADAPTED_STATE_INDICES:
            mode, alpha = choose_configuration(data, outer_train, target_index)
            configurations[(STATE_KEYS[target_index], mode, alpha)] += 1
            safe_method, safe_mode, safe_alpha = choose_safe_method(
                data, outer_train, target_index
            )
            active_method, active_mode, active_alpha = choose_safe_method(
                data, outer_train, target_index, validation_active_only=True
            )
            safe_configurations[(
                STATE_KEYS[target_index], safe_method, safe_mode, safe_alpha
            )] += 1
            active_safe_configurations[(
                STATE_KEYS[target_index], active_method, active_mode, active_alpha
            )] += 1
            fitted = fit_ridge(data, outer_train, target_index, mode, alpha)
            ensemble = fit_ensemble(
                data, outer_train, target_index, mode, alpha, rng
            )
            single_prediction = predict_ridge(
                fitted, data, outer_test, target_index
            )
            ensemble_prediction, ensemble_std, agreement = ensemble_predict(
                ensemble, data, outer_test, target_index
            )
            if safe_method == "persistence":
                safe_prediction = data["current"][outer_test, target_index]
            elif safe_method == "base_jepa":
                safe_prediction = data["base"][outer_test, target_index]
            else:
                safe_models = fit_ensemble(
                    data, outer_train, target_index, safe_mode, safe_alpha, rng
                )
                safe_prediction, _, _ = ensemble_predict(
                    safe_models, data, outer_test, target_index
                )
            if active_method == "persistence":
                active_prediction = data["current"][outer_test, target_index]
            elif active_method == "base_jepa":
                active_prediction = data["base"][outer_test, target_index]
            else:
                active_models = fit_ensemble(
                    data, outer_train, target_index,
                    active_mode, active_alpha, rng
                )
                active_prediction, _, _ = ensemble_predict(
                    active_models, data, outer_test, target_index
                )
            active_safe_prediction = np.where(
                data["active"][outer_test], active_prediction, safe_prediction
            )
            ablation_predictions = {}
            for ablation_mode in WEIGHT_MODES:
                ablation_alpha = choose_alpha_for_mode(
                    data, outer_train, target_index, ablation_mode
                )
                ablation_models = fit_ensemble(
                    data, outer_train, target_index,
                    ablation_mode, ablation_alpha, rng
                )
                ablation_predictions[ablation_mode], _, _ = ensemble_predict(
                    ablation_models, data, outer_test, target_index
                )
            for local, index in enumerate(outer_test):
                truth = data["target"][index, target_index]
                if not np.isfinite(truth):
                    continue
                numerical_rows.append({
                    "stay_id": int(data["groups"][index]),
                    "active_dka": bool(data["active"][index]),
                    "target_index": target_index,
                    "state": STATE_KEYS[target_index],
                    "truth": float(truth),
                    "current": float(data["current"][index, target_index]),
                    "scale": float(S_STD[target_index]),
                    "persistence": float(data["current"][index, target_index]),
                    "base_jepa": float(data["base"][index, target_index]),
                    "adapter": float(single_prediction[local]),
                    "ensemble_adapter": float(ensemble_prediction[local]),
                    "safe_hybrid": float(safe_prediction[local]),
                    "active_safe_hybrid": float(active_safe_prediction[local]),
                    **{
                        f"ensemble_{ablation_mode}": float(
                            predictions[local]
                        )
                        for ablation_mode, predictions in ablation_predictions.items()
                    },
                    "ensemble_std": float(ensemble_std[local]),
                    "ensemble_direction_agreement": float(agreement[local]),
                })

        for index in outer_test:
            directions = examples[index]["actual_directions"]
            for state_index in ADAPTED_STATE_INDICES:
                label = int(directions[state_index])
                if label < 0:
                    continue
                before = examples[index]["symbolic_probabilities"][state_index]
                after = apply_temperature(before[None, :], temperature)[0]
                symbolic_before.append(before)
                symbolic_after.append(after)
                symbolic_labels.append(label)
                symbolic_changed.append(label != 1)
                symbolic_stays.append(int(data["groups"][index]))

    return {
        "numerical_rows": numerical_rows,
        "symbolic_before": np.asarray(symbolic_before),
        "symbolic_after": np.asarray(symbolic_after),
        "symbolic_labels": np.asarray(symbolic_labels, dtype=np.int64),
        "symbolic_changed": np.asarray(symbolic_changed, dtype=bool),
        "symbolic_stays": np.asarray(symbolic_stays),
        "configurations": configurations,
        "safe_configurations": safe_configurations,
        "active_safe_configurations": active_safe_configurations,
    }


def abstention_metrics(probabilities, labels, threshold):
    confidence = probabilities.max(axis=1)
    accepted = confidence >= threshold
    prediction = probabilities.argmax(axis=1)
    return {
        "threshold": threshold,
        "coverage": round(float(accepted.mean()), 4),
        "accepted": int(accepted.sum()),
        "accuracy": round(float((prediction[accepted] == labels[accepted]).mean()), 4)
        if accepted.any() else None,
        "abstained": int((~accepted).sum()),
    }


def train_deployment_artifact(examples, data, output, seed=17):
    indices = np.arange(len(examples))
    rng = np.random.default_rng(seed)
    artifact = {
        "version": "1.0.0",
        "warning": (
            "Fitted on all available demo stays after cross-fitted evaluation; "
            "research use only, no causal or clinical claim."
        ),
        "state_keys": STATE_KEYS,
        "action_keys": ACTION_KEYS,
        "models": {},
    }
    probabilities = []
    labels = []
    for example in examples:
        for state_index in ADAPTED_STATE_INDICES:
            label = int(example["actual_directions"][state_index])
            if label >= 0:
                probabilities.append(example["symbolic_probabilities"][state_index])
                labels.append(label)
    artifact["symbolic_calibration"] = {
        "temperature": temperature_scale(
            np.asarray(probabilities), np.asarray(labels, dtype=np.int64)
        ),
        "recommended_min_ensemble_agreement": 0.9,
        "strict_min_ensemble_agreement": 1.0,
        "calibration_scope": "MIMIC-IV demo factual directions",
    }
    for target_index in ADAPTED_STATE_INDICES:
        method, mode, alpha = choose_safe_method(data, indices, target_index)
        models = [] if method != "adapter" else fit_ensemble(
            data, indices, target_index, mode, alpha, rng
        )
        artifact["models"][STATE_KEYS[target_index]] = {
            "target_index": target_index,
            "method": method,
            "mode": mode,
            "alpha": alpha,
            "members": models,
        }
    joblib.dump(artifact, output)
    return artifact


