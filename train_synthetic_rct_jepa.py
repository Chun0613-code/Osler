"""Train a DKA WorldModel candidate on the synthetic RCT factory output.

This is a simulator-truth training path. It is useful for checking whether the
JEPA architecture can learn the fictional RCT response surface generated by
``synthetic_rct_factory.py``. It must not be interpreted as human treatment
effect evidence, clinical validation, checkpoint promotion, or a replacement
for real randomized data.
"""

